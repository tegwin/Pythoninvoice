def get_date_diff_sql(date1: str, date2: str) -> str:
    """Get the SQL for calculating date difference based on database type."""
    config = get_db_config()
    if config.get('type') == 'mysql':
        # MySQL: DATEDIFF returns days difference
        return f"DATEDIFF({date1}, {date2})"
    else:
        # SQLite: julianday returns days difference
        return f"julianday({date1}) - julianday({date2})"


