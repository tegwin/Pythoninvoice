    def get_aged_receivables(self, as_of_date: str = None) -> Dict:
        """Get detailed aged receivables report."""
        if not as_of_date:
            as_of_date = date.today().isoformat()
        
        config = get_db_config()
        is_mysql = config.get('type') == 'mysql'
        placeholder = '%s' if is_mysql else '?'
        
        # Build date diff expression based on DB type
        if is_mysql:
            date_diff_expr = f"DATEDIFF(%s, i.due_date)"
        else:
            date_diff_expr = "julianday(?) - julianday(i.due_date)"
        
        with get_db() as conn:
            cursor = conn.cursor()
            
            cursor.execute(f'''  # nosemgrep: python.sqlalchemy.security.sqlalchemy-execute-raw-query.sqlalchemy-execute-raw-query -- column names come from a fixed list in this function; values are parameterised
                SELECT 
                    i.id, i.invoice_number, i.issue_date, i.due_date,
                    i.total, i.amount_paid, (i.total - i.amount_paid) as balance,
                    c.name as customer_name, c.email as customer_email,
                    {date_diff_expr} as days_overdue
                FROM invoices i
                LEFT JOIN customers c ON i.customer_id = c.id
                WHERE i.user_id = {placeholder}
                AND i.status IN ('sent', 'partial', 'overdue')
                AND (i.total - i.amount_paid) > 0.01
                ORDER BY i.due_date
            ''', (as_of_date, self.user_id))
            
            invoices = [dict(row) for row in cursor.fetchall()]
            
            # Categorize by aging bucket
            buckets = {
                'current': [],
                '1_30': [],
                '31_60': [],
                '61_90': [],
                'over_90': []
            }
            
            totals = {
                'current': 0,
                '1_30': 0,
                '31_60': 0,
                '61_90': 0,
                'over_90': 0,
                'total': 0
            }
            
            for inv in invoices:
                days = inv['days_overdue'] or 0
                balance = inv['balance']
                totals['total'] += balance
                
                if days <= 0:
                    buckets['current'].append(inv)
                    totals['current'] += balance
                elif days <= 30:
                    buckets['1_30'].append(inv)
                    totals['1_30'] += balance
                elif days <= 60:
                    buckets['31_60'].append(inv)
                    totals['31_60'] += balance
                elif days <= 90:
                    buckets['61_90'].append(inv)
                    totals['61_90'] += balance
                else:
                    buckets['over_90'].append(inv)
                    totals['over_90'] += balance
            
            return {
                'report_type': 'Aged Receivables',
                'as_of_date': as_of_date,
                'generated_at': datetime.now().isoformat(),
                'buckets': buckets,
                'totals': totals,
                'invoice_count': len(invoices)
            }
    
