    def get_balance_sheet(self, as_of_date: str) -> Dict:
        """
        Generate a Balance Sheet as of a specific date.
        
        Args:
            as_of_date: Date to generate balance sheet for (YYYY-MM-DD)
            
        Returns:
            Dict with assets, liabilities, and equity
        """
        config = get_db_config()
        is_mysql = config.get('type') == 'mysql'
        
        # Build aging CASE expression based on database type
        if is_mysql:
            ar_aging_case = f'''
                CASE 
                    WHEN DATEDIFF(%s, due_date) <= 0 THEN 'Current'
                    WHEN DATEDIFF(%s, due_date) <= 30 THEN '1-30 days'
                    WHEN DATEDIFF(%s, due_date) <= 60 THEN '31-60 days'
                    WHEN DATEDIFF(%s, due_date) <= 90 THEN '61-90 days'
                    ELSE '90+ days'
                END
            '''
            placeholder = '%s'
        else:
            ar_aging_case = '''
                CASE 
                    WHEN julianday(?) - julianday(due_date) <= 0 THEN 'Current'
                    WHEN julianday(?) - julianday(due_date) <= 30 THEN '1-30 days'
                    WHEN julianday(?) - julianday(due_date) <= 60 THEN '31-60 days'
                    WHEN julianday(?) - julianday(due_date) <= 90 THEN '61-90 days'
                    ELSE '90+ days'
                END
            '''
            placeholder = '?'
        
        with get_db() as conn:
            cursor = conn.cursor()
            
            # === ASSETS ===
            
            # Accounts Receivable (unpaid invoices)
            cursor.execute(f'''  # nosemgrep: python.sqlalchemy.security.sqlalchemy-execute-raw-query.sqlalchemy-execute-raw-query -- column names come from a fixed list in this function; values are parameterised
                SELECT 
                    COALESCE(SUM(total - amount_paid), 0) as accounts_receivable,
                    COUNT(*) as outstanding_invoices
                FROM invoices
                WHERE user_id = {placeholder}
                AND status IN ('sent', 'partial', 'overdue')
                AND issue_date <= {placeholder}
            ''', (self.user_id, as_of_date))
            ar_row = cursor.fetchone()
            accounts_receivable = float(ar_row['accounts_receivable'] or 0)
            
            # Accounts Receivable aging
            cursor.execute(f'''  # nosemgrep: python.sqlalchemy.security.sqlalchemy-execute-raw-query.sqlalchemy-execute-raw-query -- column names come from a fixed list in this function; values are parameterised
                SELECT 
                    {ar_aging_case} as aging_bucket,
                    SUM(total - amount_paid) as amount
                FROM invoices
                WHERE user_id = {placeholder}
                AND status IN ('sent', 'partial', 'overdue')
                AND issue_date <= {placeholder}
                GROUP BY aging_bucket
                ORDER BY 
                    CASE aging_bucket 
                        WHEN 'Current' THEN 1 
                        WHEN '1-30 days' THEN 2
                        WHEN '31-60 days' THEN 3
                        WHEN '61-90 days' THEN 4
                        ELSE 5
                    END
            ''', (as_of_date, as_of_date, as_of_date, as_of_date, self.user_id, as_of_date))
            ar_aging = [dict(row) for row in cursor.fetchall()]
            
            # === LIABILITIES ===
            
            # Accounts Payable (unpaid bills)
            cursor.execute(f'''  # nosemgrep: python.sqlalchemy.security.sqlalchemy-execute-raw-query.sqlalchemy-execute-raw-query -- column names come from a fixed list in this function; values are parameterised
                SELECT 
                    COALESCE(SUM(total - amount_paid), 0) as accounts_payable,
                    COUNT(*) as outstanding_bills
                FROM bills
                WHERE user_id = {placeholder}
                AND status IN ('approved', 'partial')
                AND bill_date <= {placeholder}
            ''', (self.user_id, as_of_date))
            ap_row = cursor.fetchone()
            accounts_payable = float(ap_row['accounts_payable'] or 0)
            
            # Accounts Payable aging
            cursor.execute(f'''  # nosemgrep: python.sqlalchemy.security.sqlalchemy-execute-raw-query.sqlalchemy-execute-raw-query -- column names come from a fixed list in this function; values are parameterised
                SELECT 
                    {ar_aging_case} as aging_bucket,
                    SUM(total - amount_paid) as amount
                FROM bills
                WHERE user_id = {placeholder}
                AND status IN ('approved', 'partial')
                AND bill_date <= {placeholder}
                GROUP BY aging_bucket
            ''', (as_of_date, as_of_date, as_of_date, as_of_date, self.user_id, as_of_date))
            ap_aging = [dict(row) for row in cursor.fetchall()]
            
            # Credit Notes Outstanding (liability - owed to customers)
            cursor.execute(f'''  # nosemgrep: python.sqlalchemy.security.sqlalchemy-execute-raw-query.sqlalchemy-execute-raw-query -- column names come from a fixed list in this function; values are parameterised
                SELECT COALESCE(SUM(total - amount_used), 0) as credit_notes_outstanding
                FROM credit_notes
                WHERE user_id = {placeholder}
                AND status IN ('issued', 'partial')
                AND issue_date <= {placeholder}
            ''', (self.user_id, as_of_date))
            cn_row = cursor.fetchone()
            credit_notes_outstanding = float(cn_row['credit_notes_outstanding'] or 0)
            
            # VAT/Tax Liability (estimated)
            cursor.execute(f'''  # nosemgrep: python.sqlalchemy.security.sqlalchemy-execute-raw-query.sqlalchemy-execute-raw-query -- column names come from a fixed list in this function; values are parameterised
                SELECT 
                    COALESCE(SUM(tax_amount), 0) as tax_collected
                FROM invoices
                WHERE user_id = {placeholder}
                AND status = 'paid'
                AND paid_at <= {placeholder}
            ''', (self.user_id, as_of_date + ' 23:59:59'))
            tax_collected = float(cursor.fetchone()['tax_collected'] or 0)
            
            cursor.execute(f'''  # nosemgrep: python.sqlalchemy.security.sqlalchemy-execute-raw-query.sqlalchemy-execute-raw-query -- column names come from a fixed list in this function; values are parameterised
                SELECT COALESCE(SUM(tax_amount), 0) as tax_paid
                FROM bills
                WHERE user_id = {placeholder} AND status = 'paid' AND updated_at <= {placeholder}
            ''', (self.user_id, as_of_date + ' 23:59:59'))
            tax_paid_bills = float(cursor.fetchone()['tax_paid'] or 0)
            
            cursor.execute(f'''  # nosemgrep: python.sqlalchemy.security.sqlalchemy-execute-raw-query.sqlalchemy-execute-raw-query -- column names come from a fixed list in this function; values are parameterised
                SELECT COALESCE(SUM(tax_amount), 0) as tax_paid
                FROM expenses
                WHERE user_id = {placeholder} AND status = 'approved' AND expense_date <= {placeholder}
            ''', (self.user_id, as_of_date))
            tax_paid_expenses = float(cursor.fetchone()['tax_paid'] or 0)
            
            estimated_tax_liability = tax_collected - tax_paid_bills - tax_paid_expenses
            
            # === EQUITY (Retained Earnings) ===
            # Calculate from all-time profit
            cursor.execute(f'''  # nosemgrep: python.sqlalchemy.security.sqlalchemy-execute-raw-query.sqlalchemy-execute-raw-query -- column names come from a fixed list in this function; values are parameterised
                SELECT COALESCE(SUM(subtotal), 0) as total_revenue
                FROM invoices
                WHERE user_id = {placeholder} AND status = 'paid' AND paid_at <= {placeholder}
            ''', (self.user_id, as_of_date + ' 23:59:59'))
            total_revenue = float(cursor.fetchone()['total_revenue'] or 0)
            
            cursor.execute(f'''  # nosemgrep: python.sqlalchemy.security.sqlalchemy-execute-raw-query.sqlalchemy-execute-raw-query -- column names come from a fixed list in this function; values are parameterised
                SELECT COALESCE(SUM(subtotal), 0) as total_credit_notes
                FROM credit_notes
                WHERE user_id = {placeholder} AND status IN ('issued', 'partial', 'applied') AND issue_date <= {placeholder}
            ''', (self.user_id, as_of_date))
            total_credit_notes = float(cursor.fetchone()['total_credit_notes'] or 0)
            
            cursor.execute(f'''  # nosemgrep: python.sqlalchemy.security.sqlalchemy-execute-raw-query.sqlalchemy-execute-raw-query -- column names come from a fixed list in this function; values are parameterised
                SELECT COALESCE(SUM(subtotal), 0) as total_bills
                FROM bills
                WHERE user_id = {placeholder} AND status = 'paid' AND updated_at <= {placeholder}
            ''', (self.user_id, as_of_date + ' 23:59:59'))
            total_bills = float(cursor.fetchone()['total_bills'] or 0)
            
            cursor.execute(f'''  # nosemgrep: python.sqlalchemy.security.sqlalchemy-execute-raw-query.sqlalchemy-execute-raw-query -- column names come from a fixed list in this function; values are parameterised
                SELECT COALESCE(SUM(net_amount), 0) as total_expenses
                FROM expenses
                WHERE user_id = {placeholder} AND status = 'approved' AND expense_date <= {placeholder}
            ''', (self.user_id, as_of_date))
            total_expenses = float(cursor.fetchone()['total_expenses'] or 0)
            
            retained_earnings = (total_revenue - total_credit_notes) - (total_bills + total_expenses)
            
            # === TOTALS ===
            total_assets = accounts_receivable
            total_liabilities = accounts_payable + credit_notes_outstanding + max(0, estimated_tax_liability)
            total_equity = retained_earnings
            
            return {
                'report_type': 'Balance Sheet',
                'as_of_date': as_of_date,
                'disclaimer': self.DISCLAIMER,
                'generated_at': datetime.now().isoformat(),
                
                'assets': {
                    'current_assets': {
                        'accounts_receivable': accounts_receivable,
                        'outstanding_invoices': ar_row['outstanding_invoices'],
                        'aging': ar_aging
                    },
                    'total_assets': total_assets,
                    'note': 'Cash and bank balances not tracked - please add from external sources'
                },
                
                'liabilities': {
                    'current_liabilities': {
                        'accounts_payable': accounts_payable,
                        'outstanding_bills': ap_row['outstanding_bills'],
                        'ap_aging': ap_aging,
                        'credit_notes_outstanding': credit_notes_outstanding,
                        'estimated_tax_liability': max(0, estimated_tax_liability)
                    },
                    'total_liabilities': total_liabilities
                },
                
                'equity': {
                    'retained_earnings': retained_earnings,
                    'total_equity': total_equity
                },
                
                'summary': {
                    'total_assets': total_assets,
                    'total_liabilities': total_liabilities,
                    'total_equity': total_equity,
                    'balance_check': round(total_assets - total_liabilities - total_equity, 2)
                }
            }
    
