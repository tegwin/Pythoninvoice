    # =========================================================================
    # PROFIT & LOSS REPORT
    # =========================================================================
    
    def get_profit_and_loss(self, start_date: str, end_date: str, 
                            compare_previous: bool = False) -> Dict:
        """
        Generate a Profit & Loss (Income Statement) report.
        
        Args:
            start_date: Start date (YYYY-MM-DD)
            end_date: End date (YYYY-MM-DD)
            compare_previous: Include comparison to previous period
            
        Returns:
            Dict with income, expenses, and profit calculations
        """
        with get_db() as conn:
            cursor = conn.cursor()
            
            # === INCOME (Revenue) ===
            # Invoices marked as paid within the period
            cursor.execute('''
                SELECT 
                    COALESCE(SUM(subtotal), 0) as sales_revenue,
                    COALESCE(SUM(tax_amount), 0) as sales_tax_collected,
                    COALESCE(SUM(total), 0) as total_invoiced,
                    COUNT(*) as invoice_count
                FROM invoices
                WHERE user_id = ? 
                AND status = 'paid'
                AND paid_at BETWEEN ? AND ?
            ''', (self.user_id, start_date, end_date + ' 23:59:59'))
            income_row = cursor.fetchone()
            
            # Get income by product/service category
            cursor.execute('''
                SELECT 
                    COALESCE(p.name, 'Uncategorized') as category,
                    SUM(ii.line_total) as amount
                FROM invoice_items ii
                JOIN invoices i ON ii.invoice_id = i.id
                LEFT JOIN products p ON ii.product_id = p.id
                WHERE i.user_id = ? 
                AND i.status = 'paid'
                AND i.paid_at BETWEEN ? AND ?
                GROUP BY p.name
                ORDER BY amount DESC
            ''', (self.user_id, start_date, end_date + ' 23:59:59'))
            income_by_category = [dict(row) for row in cursor.fetchall()]
            
            # === EXPENSES ===
            # Bills paid within the period
            cursor.execute('''
                SELECT 
                    COALESCE(SUM(subtotal), 0) as bill_expenses,
                    COALESCE(SUM(tax_amount), 0) as bill_tax_paid,
                    COUNT(*) as bill_count
                FROM bills
                WHERE user_id = ? 
                AND status = 'paid'
                AND updated_at BETWEEN ? AND ?
            ''', (self.user_id, start_date, end_date + ' 23:59:59'))
            bills_row = cursor.fetchone()
            
            # Expenses recorded within the period
            cursor.execute('''
                SELECT 
                    COALESCE(SUM(net_amount), 0) as expense_total,
                    COALESCE(SUM(tax_amount), 0) as expense_tax,
                    COUNT(*) as expense_count
                FROM expenses
                WHERE user_id = ? 
                AND status = 'approved'
                AND expense_date BETWEEN ? AND ?
            ''', (self.user_id, start_date, end_date))
            expenses_row = cursor.fetchone()
            
            # Get expenses by category
            cursor.execute('''
                SELECT 
                    COALESCE(category, 'Uncategorized') as category,
                    SUM(net_amount) as amount
                FROM expenses
                WHERE user_id = ? 
                AND status = 'approved'
                AND expense_date BETWEEN ? AND ?
                GROUP BY category
                ORDER BY amount DESC
            ''', (self.user_id, start_date, end_date))
            expenses_by_category = [dict(row) for row in cursor.fetchall()]
            
            # Get bill expenses by COA category
            cursor.execute('''
                SELECT 
                    COALESCE(coa.name, 'Uncategorized') as category,
                    SUM(bi.total) as amount
                FROM bill_items bi
                JOIN bills b ON bi.bill_id = b.id
                LEFT JOIN chart_of_accounts coa ON bi.coa_id = coa.id
                WHERE b.user_id = ? 
                AND b.status = 'paid'
                AND b.updated_at BETWEEN ? AND ?
                GROUP BY coa.name
                ORDER BY amount DESC
            ''', (self.user_id, start_date, end_date + ' 23:59:59'))
            bill_expenses_by_category = [dict(row) for row in cursor.fetchall()]
            
            # === CREDIT NOTES (reduce revenue) ===
            cursor.execute('''
                SELECT 
                    COALESCE(SUM(subtotal), 0) as credit_notes_total,
                    COALESCE(SUM(tax_amount), 0) as credit_notes_tax,
                    COUNT(*) as credit_note_count
                FROM credit_notes
                WHERE user_id = ? 
                AND status IN ('issued', 'partial', 'applied')
                AND issue_date BETWEEN ? AND ?
            ''', (self.user_id, start_date, end_date))
            credit_row = cursor.fetchone()
            
            # === CALCULATIONS ===
            gross_revenue = float(income_row['sales_revenue'] or 0)
            credit_notes = float(credit_row['credit_notes_total'] or 0) if credit_row else 0
            net_revenue = gross_revenue - credit_notes
            
            total_expenses = (
                float(bills_row['bill_expenses'] or 0) + 
                float(expenses_row['expense_total'] or 0)
            )
            
            gross_profit = net_revenue - total_expenses
            
            # Tax calculations
            tax_collected = float(income_row['sales_tax_collected'] or 0)
            credit_note_tax = float(credit_row['credit_notes_tax'] or 0) if credit_row else 0
            net_tax_collected = tax_collected - credit_note_tax
            
            tax_paid = (
                float(bills_row['bill_tax_paid'] or 0) + 
                float(expenses_row['expense_tax'] or 0)
            )
            
            net_tax_position = net_tax_collected - tax_paid
            
            # === PREVIOUS PERIOD COMPARISON ===
            previous_period = None
            if compare_previous:
                # Calculate previous period dates - handle both string and date objects
                if isinstance(start_date, str):
                    start = datetime.strptime(start_date, '%Y-%m-%d')
                else:
                    start = datetime.combine(start_date, datetime.min.time())
                if isinstance(end_date, str):
                    end = datetime.strptime(end_date, '%Y-%m-%d')
                else:
                    end = datetime.combine(end_date, datetime.min.time())
                period_days = (end - start).days + 1
                prev_end = start - timedelta(days=1)
                prev_start = prev_end - timedelta(days=period_days - 1)
                
                previous_period = self.get_profit_and_loss(
                    prev_start.strftime('%Y-%m-%d'),
                    prev_end.strftime('%Y-%m-%d'),
                    compare_previous=False
                )
            
            return {
                'report_type': 'Profit & Loss',
                'period': {
                    'start_date': start_date,
                    'end_date': end_date
                },
                'disclaimer': self.DISCLAIMER,
                'generated_at': datetime.now().isoformat(),
                
                'income': {
                    'gross_revenue': gross_revenue,
                    'credit_notes': credit_notes,
                    'net_revenue': net_revenue,
                    'invoice_count': income_row['invoice_count'],
                    'credit_note_count': credit_row['credit_note_count'] if credit_row else 0,
                    'by_category': income_by_category
                },
                
                'expenses': {
                    'bills_total': float(bills_row['bill_expenses'] or 0),
                    'expenses_total': float(expenses_row['expense_total'] or 0),
                    'total_expenses': total_expenses,
                    'bill_count': bills_row['bill_count'],
                    'expense_count': expenses_row['expense_count'],
                    'by_category': expenses_by_category,
                    'bills_by_category': bill_expenses_by_category
                },
                
                'profit': {
                    'gross_profit': gross_profit,
                    'profit_margin': (gross_profit / net_revenue * 100) if net_revenue > 0 else 0
                },
                
                'tax': {
                    'collected': net_tax_collected,
                    'paid': tax_paid,
                    'net_position': net_tax_position,
                    'note': 'Positive = VAT owed to HMRC, Negative = VAT refund due'
                },
                
                'previous_period': previous_period
            }
    
